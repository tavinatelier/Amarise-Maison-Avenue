export function getPillar(slug: string) {
  return pillars.find((p) => p.slug === slug);
}

export function getFamiliesByPillar(pillarSlug: string) {
  const pillar = getPillar(pillarSlug);
  return pillar?.families ?? [];
}

export function getMicroCategoriesByFamily(pillarSlug: string, familySlug: string) {
  return microCategories.filter((mc) => mc.pillarSlug === pillarSlug && mc.familySlug === familySlug);
}

export function getProductsByPillar(pillarSlug: string) {
  return sampleProducts.filter((p) => p.pillarSlug === pillarSlug && !p.isDraft);
}

export function getProductsByFamily(pillarSlug: string, familySlug: string) {
  return sampleProducts.filter((p) => p.pillarSlug === pillarSlug && p.familySlug === familySlug && !p.isDraft);
}

export function getProductBySlug(slug: string) {
  return sampleProducts.find((p) => p.slug === slug);
}

export function getRelatedProducts(product: CatalogProduct, limit = 4) {
  return sampleProducts
    .filter((p) => p.id !== product.id && (p.pillarSlug === product.pillarSlug || p.familySlug === product.familySlug) && !p.isDraft)
    .slice(0, limit);
}

export function getFeaturedProducts(limit = 8) {
  return sampleProducts.filter((p) => p.isFeatured && !p.isDraft).slice(0, limit);
}

export function getLowStockProducts(threshold = 10) {
  return sampleProducts.filter((p) => p.inventory < threshold && p.inStock && !p.isDraft);
}
